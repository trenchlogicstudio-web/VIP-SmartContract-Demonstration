// Writes sessions-synthetic.csv to standard output: 400 invented guests over
// one quarter, each with a typical loss drawn around €1,500 and two to ten
// sessions, about two in three of them losing. Deterministic: the same seed
// gives the same file on every run. No operator's data is used or implied.
//
//   node samples/make-sessions.js > samples/sessions-synthetic.csv
'use strict';

function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const random = mulberry32(20261122);
function normal() {
  let u = 0, v = 0;
  while (u === 0) u = random();
  while (v === 0) v = random();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

const start = Date.UTC(2026, 6, 1), days = 92, rows = [];
for (let g = 1; g <= 400; g++) {
  const guest = 'G' + String(g).padStart(4, '0');
  const typical = 1500 * Math.exp(0.9 * normal());
  const visits = 2 + Math.floor(random() * 9);
  for (let v = 0; v < visits; v++) {
    const date = new Date(start + Math.floor(random() * days) * 86400000).toISOString().slice(0, 10);
    const size = typical * Math.exp(0.6 * normal());
    const loss = random() < 0.68 ? size : -0.6 * size;
    rows.push([date, guest, (Math.round(loss * 100) / 100).toFixed(2)]);
  }
}
rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : 0));
process.stdout.write([
  '# Synthetic past sessions for the VIP replay, generated by samples/make-sessions.js. Not data from any operator.',
  '# © 2026 Miloš Petrović (Trench Logic Studio) · MIT License',
  'guest,date,loss_eur',
  ...rows.map(([date, guest, loss]) => `${guest},${date},${loss}`),
].join('\n') + '\n');
